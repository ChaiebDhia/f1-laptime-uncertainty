"""Markdown report generation from computed results (no numbers are typed by hand)."""

from __future__ import annotations

from datetime import date

import pandas as pd

from . import __version__
from .validation import SCHEME_LABELS

K_PLAUSIBLE = (-0.12, -0.02)  # s/lap; heuristic, see docs/METHODS.md


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _fmt_summary(s: pd.DataFrame, alpha: float) -> pd.DataFrame:
    out = pd.DataFrame(
        {
            "Model": s["model"],
            "n laps": s["n"],
            "MAE (s)": s["MAE_s"],
            "RMSE (s)": s["RMSE_s"],
            "RMSE 95% CI": [
                f"{a:.3f} to {b:.3f}" for a, b in zip(s["RMSE_lo"], s["RMSE_hi"], strict=True)
            ],
            f"Coverage (target {1 - alpha:.0%})": [f"{c:.1%}" for c in s["coverage"]],
            "Mean width (s)": s["mean_width_s"],
            "Interval score": s["interval_score"],
        }
    )
    return out


def _findings(pooled: dict, alpha: float) -> list[str]:
    lines = []
    for scheme, s in pooled.items():
        best = s.loc[s["RMSE_s"].idxmin()]
        cov = ", ".join(f"{r['model'].split(' (')[0]} {r['coverage']:.0%}" for _, r in s.iterrows())
        best_is = s.loc[s["interval_score"].idxmin(), "model"]
        lines.append(
            f"- **{SCHEME_LABELS[scheme]}**: lowest RMSE is {best['model']} "
            f"({best['RMSE_s']:.3f} s); lowest interval score is {best_is}. "
            f"Empirical coverage of the nominal {1 - alpha:.0%} intervals: {cov}."
        )
    return lines


def _param_checks(par: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for race, g in par.groupby("race", sort=False):
        g = g.set_index("param")
        k = g.loc["k_fuel_track", "estimate"]
        ordered = (
            g.loc["g_SOFT", "estimate"]
            >= g.loc["g_MEDIUM", "estimate"]
            >= g.loc["g_HARD", "estimate"]
        )
        rows.append(
            {
                "Race": race,
                "k in heuristic band": "yes" if K_PLAUSIBLE[0] <= k <= K_PLAUSIBLE[1] else "NO",
                "g ordered soft>=med>=hard": "yes" if ordered else "no",
                "any parameter at bound": "YES" if g["at_bound"].any() else "no",
            }
        )
    return pd.DataFrame(rows)


def write_report(
    path,
    *,
    alpha: float,
    races: dict,
    droplogs: dict,
    pooled: dict,
    by_race: pd.DataFrame,
    params: pd.DataFrame,
    figures: dict,
    synthetic: bool,
    n_trimmed: dict,
) -> None:
    out = [
        "# F1 lap-time uncertainty study: results",
        "",
        f"_Generated by f1lap {__version__} on {date.today().isoformat()}. "
        f"Nominal interval level {1 - alpha:.0%}. All numbers below are computed, not typed._",
        "",
    ]
    if synthetic:
        out += [
            "> **SYNTHETIC DATA.** These results come from generated races with known "
            "parameters and verify the code only. They say nothing about real F1 behaviour.",
            "",
        ]
    out += ["## 1. Data", ""]
    rows = []
    for name, df in races.items():
        raw = (
            int(droplogs[name].iloc[0]["remaining"]) if droplogs.get(name) is not None else len(df)
        )
        rows.append(
            {
                "Race": name,
                "Raw laps": raw,
                "Clean laps": len(df),
                "Drivers": df["driver"].nunique(),
                "Stints": df["stint_id"].nunique(),
                "Laps trimmed from fit": n_trimmed.get(name, 0),
            }
        )
    out += [md_table(pd.DataFrame(rows)), ""]
    for name, log in droplogs.items():
        if log is not None:
            out += [
                f"<details><summary>Cleaning log: {name}</summary>\n",
                md_table(log),
                "\n</details>",
                "",
            ]

    out += ["## 2. Out-of-sample validation (pooled over races)", ""]
    for scheme, s in pooled.items():
        out += [f"### {SCHEME_LABELS[scheme]}", "", md_table(_fmt_summary(s, alpha)), ""]
    out += ["**Headline**", ""] + _findings(pooled, alpha) + [""]
    out += [
        "**How to read this.** RMSE and MAE measure accuracy. Coverage measures whether the "
        "intervals are honest: a model whose 90% intervals cover 60% of outcomes is "
        "overconfident however accurate its mean. The interval score (lower is better) "
        "combines sharpness and calibration. RMSE confidence intervals resample whole "
        "stints because laps within a stint are not independent.",
        "",
    ]
    out += ["### Per race", "", md_table(by_race.round(3)), ""]

    out += [
        "## 3. Fitted physical parameters",
        "",
        md_table(params.round(4), "{:.4f}"),
        "",
        "Sanity checks (heuristic, not proof):",
        "",
        md_table(_param_checks(params)),
        "",
        f"`k` is the combined fuel-burn and track-evolution effect; engineering rules of thumb "
        f"(about 0.03 s/kg, 1.5 to 2 kg burned per lap) suggest roughly {K_PLAUSIBLE[0]} to "
        f"{K_PLAUSIBLE[1]} s/lap. A parameter at its bound means the data could not identify it "
        f"and its confidence interval should not be trusted.",
        "",
    ]

    out += ["## 4. Figures", ""]
    for caption, f in figures.items():
        out += [f"**{caption}**", "", f"![{caption}]({f})", ""]
    out += [
        "## 5. Limitations",
        "",
        "- Fuel burn and track evolution are not separable from lap number alone.",
        "- Tyre age and race lap are correlated; identifiability comes from staggered stints.",
        "- Traffic, dirty air, engine modes, fuel saving and weather are not modelled; they "
        "appear as residual noise (see diagnostics).",
        "- Per-race fits: parameters are not comparable across circuits without a "
        "hierarchical model.",
        "- Unofficial public timing data; not affiliated with Formula 1 or any team.",
        "",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
